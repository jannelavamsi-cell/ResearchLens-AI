"""
Multi-format document export module for ResearchLens AI.
Exports reports, matrices, and literature reviews to Markdown, DOCX, PDF, and BibTeX.
"""

import io
import logging
import re
from typing import Any, Dict, List, Optional

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt, RGBColor
from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer

from modules.references import generate_references_list

logger = logging.getLogger("researchlens.export")


def clean_markdown_for_text(md: str) -> str:
    """Strips markdown syntax for clean plain-text inclusion."""
    text = re.sub(r"#+\s*", "", md)
    text = re.sub(r"\*\*([^*]+)\*\*", r"\1", text)
    text = re.sub(r"\*([^*]+)\*", r"\1", text)
    text = re.sub(r">+\s*", "", text)
    return text.strip()


def export_to_markdown(title: str, content: str, references: Optional[List[str]] = None) -> str:
    """Generates standard Markdown document with title, body, and references."""
    lines = [f"# {title}\n", content.strip(), "\n"]
    if references:
        lines.append("## References\n")
        for r in references:
            lines.append(f"- {r}")
        lines.append("\n")
    return "\n".join(lines)


def export_to_docx(
    title: str,
    sections: List[Dict[str, str]],
    table_data: Optional[List[List[str]]] = None,
    references: Optional[List[str]] = None,
    disclaimer: Optional[str] = None,
) -> io.BytesIO:
    """
    Builds a styled Word document (.docx) with headings, bullet points, tables, and references.
    """
    doc = Document()

    # Document Title
    h1 = doc.add_heading(title, level=0)
    h1.alignment = WD_ALIGN_PARAGRAPH.CENTER

    # Subtitle / Header
    subtitle = doc.add_paragraph("Generated by ResearchLens AI — Grounded Literature Intelligence")
    subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER
    subtitle.runs[0].font.size = Pt(10)
    subtitle.runs[0].font.italic = True
    subtitle.runs[0].font.color.rgb = RGBColor(120, 120, 120)

    # Disclaimer Callout
    if disclaimer:
        callout = doc.add_paragraph()
        callout_run = callout.add_run(f"Academic Notice: {disclaimer}")
        callout_run.font.italic = True
        callout_run.font.size = Pt(9.5)
        callout_run.font.color.rgb = RGBColor(180, 50, 50)

    doc.add_paragraph()

    # Sections
    for sec in sections:
        sec_title = sec.get("title", "")
        sec_body = sec.get("content", "")

        if sec_title:
            doc.add_heading(sec_title, level=1)

        # Parse paragraphs and bullet points
        lines = sec_body.split("\n")
        for line in lines:
            line_str = line.strip()
            if not line_str:
                continue
            if line_str.startswith("- ") or line_str.startswith("* "):
                p = doc.add_paragraph(clean_markdown_for_text(line_str[2:]), style="List Bullet")
            elif line_str.startswith("> "):
                p = doc.add_paragraph(clean_markdown_for_text(line_str[2:]))
                p.runs[0].font.italic = True
            else:
                doc.add_paragraph(clean_markdown_for_text(line_str))

    # Optional Table Data
    if table_data and len(table_data) > 1:
        doc.add_heading("Comparison Matrix", level=1)
        headers = table_data[0]
        rows = table_data[1:]
        t = doc.add_table(rows=len(rows) + 1, cols=len(headers))
        t.style = "Table Grid"

        # Headers
        for col_idx, h in enumerate(headers):
            cell = t.cell(0, col_idx)
            cell.text = str(h)
            for r in cell.paragraphs[0].runs:
                r.font.bold = True

        # Rows
        for row_idx, row in enumerate(rows):
            for col_idx, val in enumerate(row):
                t.cell(row_idx + 1, col_idx).text = str(val)

    # References
    if references:
        doc.add_heading("References", level=1)
        for ref in references:
            doc.add_paragraph(ref, style="List Bullet")

    buf = io.BytesIO()
    doc.save(buf)
    buf.seek(0)
    return buf


def export_to_pdf(
    title: str,
    sections: List[Dict[str, str]],
    references: Optional[List[str]] = None,
    disclaimer: Optional[str] = None,
) -> io.BytesIO:
    """
    Builds a styled PDF document with headers, content blocks, and references using ReportLab.
    """
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=letter,
        rightMargin=54,
        leftMargin=54,
        topMargin=54,
        bottomMargin=54,
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Heading1"],
        fontSize=20,
        leading=24,
        textColor=colors.HexColor("#1A365D"),
        spaceAfter=8,
        alignment=1,
    )
    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontSize=9,
        leading=12,
        textColor=colors.HexColor("#718096"),
        alignment=1,
        spaceAfter=15,
    )
    disclaimer_style = ParagraphStyle(
        "DocDisclaimer",
        parent=styles["Normal"],
        fontSize=8.5,
        leading=11,
        textColor=colors.HexColor("#C53030"),
        spaceAfter=15,
    )
    h1_style = ParagraphStyle(
        "SectionH1",
        parent=styles["Heading2"],
        fontSize=13,
        leading=17,
        textColor=colors.HexColor("#2B6CB0"),
        spaceBefore=12,
        spaceAfter=6,
    )
    body_style = ParagraphStyle(
        "SectionBody",
        parent=styles["Normal"],
        fontSize=9.5,
        leading=14,
        spaceAfter=6,
    )

    story = []

    # Title & Subtitle
    story.append(Paragraph(title, title_style))
    story.append(Paragraph("ResearchLens AI — Grounded Literature Analysis", subtitle_style))

    if disclaimer:
        story.append(Paragraph(f"<b>Academic Notice:</b> {disclaimer}", disclaimer_style))

    story.append(Spacer(1, 10))

    # Sections
    for sec in sections:
        sec_title = sec.get("title", "")
        sec_body = sec.get("content", "")

        if sec_title:
            story.append(Paragraph(sec_title, h1_style))

        lines = sec_body.split("\n")
        for line in lines:
            line_str = line.strip()
            if not line_str:
                continue
            clean_l = clean_markdown_for_text(line_str)
            # Escape HTML characters for ReportLab Paragraph
            clean_l = clean_l.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            if line_str.startswith("- ") or line_str.startswith("* "):
                clean_l = f"&bull; {clean_l}"
            story.append(Paragraph(clean_l, body_style))

        story.append(Spacer(1, 8))

    # References
    if references:
        story.append(Paragraph("References", h1_style))
        for r in references:
            r_esc = r.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            story.append(Paragraph(f"&bull; {r_esc}", body_style))

    doc.build(story)
    buf.seek(0)
    return buf


def export_bibtex_file(papers: List[Dict[str, Any]]) -> str:
    """Generates a complete BibTeX bibliography bundle for downloading."""
    refs = generate_references_list(papers, style="bibtex")
    return "\n\n".join(refs)
